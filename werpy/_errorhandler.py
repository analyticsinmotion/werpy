"""
Input validation and consistent exceptions for werpy public functions.
"""

import math
import numbers
import sys
from fractions import Fraction
from typing import TypeAlias

import numpy as np
from numpy.typing import NDArray

from .exceptions import WerpyTypeError, WerpyValueError

# The sequence types accepted as a batch of texts, and the full set of accepted inputs.
# These are the types checked by error_handler below.
TextBatch: TypeAlias = list[str] | tuple[str, ...] | NDArray[np.str_] | NDArray[np.object_]
TextInput: TypeAlias = str | TextBatch

# The inputs that error_handler returns and that the compiled routers in _metrics accept: a tuple becomes a list.
MetricsInput: TypeAlias = str | list[str] | NDArray[np.str_] | NDArray[np.object_]

_STR_TYPE = frozenset((str,))
_PLAIN_NUMBER_TYPES = frozenset((int, float))
_FLOAT_MAX = sys.float_info.max


def error_handler(
    reference: object, hypothesis: object, allow_empty: bool = True
) -> tuple[MetricsInput, MetricsInput]:
    """
    Validate inputs, raise consistent exceptions, and return the inputs in the form that the metrics are computed on.

    This function does not compute metrics. Computation is handled by:
    - _metrics.metrics (router) for strings and batches
    - _metrics.calculations for a single pair

    The checks run in this order, and the first check that fails raises its exception:
    1. the type of the reference and, for a numpy array, its number of dimensions;
    2. the type of the hypothesis and, for a numpy array, its number of dimensions;
    3. the kind: both strings, or both lists, tuples or numpy arrays;
    4. for two batches, the number of elements;
    5. for two batches, whether they are empty, when allow_empty is False;
    6. the type of every element of the reference batch, then of the hypothesis batch;
    7. a blank reference string, or the first blank element of the reference batch.

    Parameters
    ----------
    reference : str, list, tuple or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list, tuple or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.
    allow_empty : bool, optional
        If False, two empty lists, tuples or numpy arrays raise WerpyValueError. The default is True.

    Raises
    ------
    WerpyTypeError
        if an input is not a string, a list, a tuple or a numpy array, if a numpy array does not have exactly one
        dimension, if one input is a string and the other is not, or if an element of a list, tuple or numpy array is
        not a string.
    WerpyValueError
        if the two lists, tuples or numpy arrays do not contain the same number of elements, if they are empty and
        allow_empty is False, or if a reference is blank, either as a single string or as an element of a list,
        tuple or numpy array.

    Returns
    -------
    tuple
        The reference and the hypothesis. A tuple is returned as a list. Every other input is returned unchanged.
    """
    # Two strings: only the blank reference check applies.
    if isinstance(reference, str) and isinstance(hypothesis, str):
        if not reference.strip():
            raise WerpyValueError(
                "Invalid input: reference must not be blank, and reference and hypothesis cannot both be empty."
            )
        return reference, hypothesis

    reference = check_text_input("reference", reference)
    hypothesis = check_text_input("hypothesis", hypothesis)

    # One input is a string and the other is a list, a tuple or a numpy array.
    if isinstance(reference, str) or isinstance(hypothesis, str):
        raise WerpyTypeError(
            "Reference and hypothesis must both be strings, or both be lists, tuples or numpy arrays."
        )

    if len(reference) != len(hypothesis):
        raise WerpyValueError(
            "The Reference and Hypothesis input parameters must have the same number of elements."
        )
    if not allow_empty and len(reference) == 0:
        raise WerpyValueError(
            "Reference and hypothesis must not be empty. The Word Error Rate is not defined for empty sequences."
        )

    check_elements("reference", reference)
    check_elements("hypothesis", hypothesis)

    # The index of the first blank reference is found only when the batch holds one.
    if not all(map(str.strip, reference)):
        for index, element in enumerate(reference):
            if not element.strip():
                raise WerpyValueError(
                    f"Invalid input: reference must not be blank. A blank reference was found at index {index}."
                )

    if isinstance(reference, tuple):
        reference = list(reference)
    if isinstance(hypothesis, tuple):
        hypothesis = list(hypothesis)
    return reference, hypothesis


def check_text_input(name: str, value: object) -> TextInput:
    """
    Check the type of one text input and, for a numpy array, its number of dimensions, and return the input.

    A text input is a string, a list, a tuple, or a numpy array with one dimension. WerpyTypeError is raised for an
    input of any other type, and for a numpy array with any other number of dimensions. The message names the input.
    """
    if isinstance(value, (str, list, tuple)):
        return value
    if isinstance(value, np.ndarray):
        if value.ndim != 1:
            raise WerpyTypeError(
                f"{name} must be a one-dimensional numpy array, not an array with {value.ndim} dimensions."
            )
        return value
    raise WerpyTypeError(
        f"{name} must be a str, or a list, tuple or one-dimensional numpy array of str, not {type(value).__name__}."
    )


def check_elements(name: str, batch: TextBatch) -> None:
    """
    Raise WerpyTypeError for the first element of a list, tuple or numpy array that is not a string.

    The elements of a numpy array of dtype U are always strings, so they are not checked one by one. For any other
    batch, the types of all elements are collected in one pass, and the index of the first element that is not a
    string is found only when that pass finds such an element.
    """
    if isinstance(batch, np.ndarray) and batch.dtype.kind == "U":
        return
    if set(map(type, batch)) <= _STR_TYPE:
        return
    for index, element in enumerate(batch):
        if not isinstance(element, str):
            raise element_error(name, element, index)


def element_error(name: str, element: object, index: int) -> WerpyTypeError:
    """
    Return the WerpyTypeError for an element of a list, tuple or numpy array that is not a string. The message names
    the input, the type of the element and its index.
    """
    return WerpyTypeError(
        f"Every element of {name} must be a str. An element of type {type(element).__name__} was found at index "
        f"{index}."
    )


def check_weights(
    insertions_weight: float, deletions_weight: float, substitutions_weight: float
) -> tuple[float, float, float]:
    """
    Check the three weights of werp, werps and summaryp, and return them.

    When each weight is a plain int or float that is finite and at least 0, the three weights are returned unchanged.
    Otherwise check_weight checks each weight in argument order, and the three weights are returned as floats.
    """
    if (
        type(insertions_weight) in _PLAIN_NUMBER_TYPES
        and type(deletions_weight) in _PLAIN_NUMBER_TYPES
        and type(substitutions_weight) in _PLAIN_NUMBER_TYPES
    ):
        if (
            0 <= insertions_weight <= _FLOAT_MAX
            and 0 <= deletions_weight <= _FLOAT_MAX
            and 0 <= substitutions_weight <= _FLOAT_MAX
        ):
            return insertions_weight, deletions_weight, substitutions_weight
    return (
        check_weight("insertions_weight", insertions_weight),
        check_weight("deletions_weight", deletions_weight),
        check_weight("substitutions_weight", substitutions_weight),
    )


def check_weight(name: str, weight: object) -> float:
    """
    Check one weight and return it as a float.

    A weight is a real number: an instance of numbers.Real that is not a bool, a numpy.bool_ or a numpy.timedelta64.
    WerpyTypeError is raised for any other value. WerpyValueError is raised for a weight that, as a float, is
    negative, NaN or infinite. The message names the weight.
    """
    if isinstance(weight, (bool, np.bool_, np.timedelta64)) or not isinstance(weight, numbers.Real):
        raise WerpyTypeError(f"{name} must be a real number, such as an int or a float, not {type(weight).__name__}.")
    try:
        number = float(weight)
    except OverflowError:
        # An int or a fraction that is too large for a float is out of range.
        number = math.inf
    if not 0.0 <= number <= _FLOAT_MAX:
        raise WerpyValueError(f"{name} must be a finite number of at least 0.")
    return number



def substitution_order(insertions_weight: float, deletions_weight: float, substitutions_weight: float) -> int:
    """
    Return how the weights of werp, werps and summaryp rank the alignments that have the fewest edits.

    Among those alignments, the weighted cost changes with the number of substitutions only. The result is 1 when a
    substitution weighs more than the mean of an insertion and a deletion, so that the alignment with the fewest
    substitutions has the lowest weighted cost, and -1 when it weighs less, so that the alignment with the most
    substitutions has the lowest weighted cost. The result is 0 when a substitution weighs exactly that mean, so that
    all these alignments have the same weighted cost. Each weight is compared as its float value, and the comparison is
    exact.
    """
    if insertions_weight == deletions_weight == substitutions_weight:
        return 0
    insertions, deletions = float(insertions_weight), float(deletions_weight)
    double = 2.0 * substitutions_weight
    total = insertions + deletions
    if double != total:
        # double is exact and rounding is monotonic, so the rounded sum is ordered as the exact sum.
        return 1 if double > total else -1
    if total == math.inf:
        exact = 2 * Fraction(float(substitutions_weight)) - Fraction(insertions) - Fraction(deletions)
        return (exact > 0) - (exact < 0)
    # error is the exact rounding error of total (TwoSum), so that the exact sum is total + error.
    part = total - insertions
    error = (insertions - (total - part)) + (deletions - part)
    return (error < 0) - (error > 0)
