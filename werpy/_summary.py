"""
This module provides a summary function to display a complete breakdown of the calculated results, returned in a
pandas DataFrame or, with output="polars", in a polars DataFrame or, with output="records", in a list of dictionaries.

This module defines the following function:
    - summary(reference, hypothesis, *, output="pandas")
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Literal, cast, overload

import numpy as np
from ._errorhandler import TextInput, error_handler
from ._metrics import metrics
from ._output import SummaryRecord, check_output, dataframe, polars_dataframe

if TYPE_CHECKING:
    import pandas as pd
    import polars as pl


@overload
def summary(reference: TextInput, hypothesis: TextInput, *, output: Literal["pandas"] = ...) -> pd.DataFrame: ...


@overload
def summary(reference: TextInput, hypothesis: TextInput, *, output: Literal["polars"]) -> pl.DataFrame: ...


@overload
def summary(reference: TextInput, hypothesis: TextInput, *, output: Literal["records"]) -> list[SummaryRecord]: ...


def summary(
    reference: TextInput, hypothesis: TextInput, *, output: Literal["pandas", "polars", "records"] = "pandas"
) -> pd.DataFrame | pl.DataFrame | list[SummaryRecord]:
    """
    This function provides a comprehensive breakdown of the calculated results including the WER, Levenshtein
    Distance and all the insertion, deletion and substitution errors.

    The counts and the word lists come from an alignment of the reference and hypothesis words with the fewest edits.
    When several such alignments exist, summary() reads the texts from the last word back to the first and takes, at
    each step, the first of these moves that keeps the fewest edits: a match, a substitution, an insertion, then a
    deletion.

    The memory that summary() uses grows with the number of words in the reference and the hypothesis, so it can
    compare long transcripts. The time grows with the product of the two numbers of words.

    werpy compares words exactly as they are written. Words that differ in case, punctuation or the way a character
    is stored count as different words. To compare texts from different sources, pass both through normalize() first.

    The pandas DataFrame needs pandas, which the pandas extra of werpy installs: pip install "werpy[pandas]". The
    polars DataFrame of output="polars" needs polars, which the polars extra installs: pip install "werpy[polars]".
    The list of dictionaries of output="records" works with a plain install of werpy.

    Parameters
    ----------
    reference : str, list, tuple or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list, tuple or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.
    output : str, optional
        The form of the results, given by keyword only: "pandas", the default, for a pandas DataFrame, "polars" for a
        polars DataFrame, or "records" for a list of dictionaries.

    Raises
    ------
    werpy.exceptions.WerpyTypeError
        If the reference or the hypothesis is not a string, a list, a tuple or a numpy array, if a numpy array does
        not have exactly one dimension, if one of them is a string and the other is a list, a tuple or a numpy array,
        if an element of a list, tuple or numpy array is not a string, for example a number or None, or if output is
        not a string.
    werpy.exceptions.WerpyValueError
        If a reference is blank, either as a single string or as an element of a list, tuple or numpy array, if
        the reference and hypothesis lists, tuples or arrays do not contain the same number of elements, or if output
        is a string other than "pandas", "polars" and "records".
    ImportError
        If output is "pandas" and pandas cannot be imported, or if output is "polars" and polars cannot be imported.
        The reference, the hypothesis and output are checked first.

    Returns
    -------
    pandas.core.frame.DataFrame, polars.DataFrame or list
        With output="pandas", returns a dataframe containing the following nine columns:
            wer - The Word Error Rate
            ld - The Levenshtein distance
            m - The number of words in the reference sequence
            insertions - the number of hypothesis words that the alignment pairs with no reference word
            deletions - the number of reference words that the alignment pairs with no hypothesis word
            substitutions - the number of reference words that the alignment pairs with a different hypothesis word
            inserted_words - list of inserted words
            deleted_words - list of deleted words
            substituted_words - list of substitutions. Each substitution will be shown as a tuple with the reference
            word and the hypothesis word. For example: [(cited, sighted), (abnormally, normally)]
        With output="polars", returns a polars DataFrame with the same nine columns in the same order. wer is
        Float64, the counts are Int64, and inserted_words and deleted_words are lists of String. substituted_words is
        a list of Struct values, each with the fields reference and hypothesis. Empty lists give a DataFrame with no
        rows and these types.
        With output="records", returns a list with one dictionary for each pair of texts, in the same order. The keys
        of each dictionary are the nine columns, in the same order. wer is a float, the counts are ints and the word
        lists are lists. A pair of strings gives a list that holds one dictionary.
    """
    reference, hypothesis = error_handler(reference, hypothesis)
    form = check_output("summary", output)
    result = metrics(reference, hypothesis)

    # Batch rows (n, 9)
    if isinstance(result, np.ndarray) and result.ndim == 2:
        word_error_rate_breakdown = result.tolist()
    else:
        # Single row - wrap in list for DataFrame
        word_error_rate_breakdown = [result.tolist() if hasattr(result, 'tolist') else list(result)]

    columns = [
        "wer",
        "ld",
        "m",
        "insertions",
        "deletions",
        "substitutions",
        "inserted_words",
        "deleted_words",
        "substituted_words",
    ]
    if form == "records":
        return cast(list[SummaryRecord], [dict(zip(columns, row)) for row in word_error_rate_breakdown])
    if form == "polars":
        return polars_dataframe(word_error_rate_breakdown, columns)
    df = dataframe(word_error_rate_breakdown, columns)
    return df
