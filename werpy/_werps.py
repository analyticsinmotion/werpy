"""
This module provides a function for calculating a list of weighted Word Error Rate for each of the reference and
hypothesis texts. It allows varying weights to be assigned to the insertion, deletion and substitution errors.

This module defines the following function:
    - werps(reference, hypothesis, insertions_weight=1, deletions_weight=1, substitutions_weight=1)
"""

from typing import cast

import numpy as np
from ._errorhandler import TextInput, check_weights, error_handler, substitution_order
from ._metrics import metrics_fast
from ._weighted import metrics_fast_weighted


def werps(
    reference: TextInput,
    hypothesis: TextInput,
    insertions_weight: float = 1,
    deletions_weight: float = 1,
    substitutions_weight: float = 1,
) -> list[float]:
    """
    This function calculates a list of weighted Word Error Rates for each of the reference and hypothesis texts. It
    allows the insertion, deletion and substitution errors to be penalized or weighted at different rates.

    The errors are counted on an alignment of the reference and hypothesis words with the fewest edits, as for the Word
    Error Rate. When several such alignments exist, the one with the lowest weighted cost is used. This is the alignment
    with the fewest substitutions when a substitution weighs more than the mean of an insertion and a deletion, and the
    alignment with the most substitutions when it weighs less. When a substitution weighs exactly that mean, for example
    when the three weights are equal, all these alignments have the same weighted cost, and the alignment of summary()
    is used.

    Parameters
    ----------
    reference : str, list, tuple or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list, tuple or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.
    insertions_weight: int or float, optional
        The weight multiplier for an insertion error. A finite real number of at least 0.
    deletions_weight: int or float, optional
        The weight multiplier for a deletion error. A finite real number of at least 0.
    substitutions_weight: int or float, optional
        The weight multiplier for a substitution error. A finite real number of at least 0.

    Raises
    ------
    werpy.exceptions.WerpyTypeError
        If the reference or the hypothesis is not a string, a list, a tuple or a numpy array, if a numpy array does
        not have exactly one dimension, if one of them is a string and the other is a list, a tuple or a numpy array,
        if an element of a list, tuple or numpy array is not a string, for example a number or None, or if a weight
        is not a real number, for example a string, None, a bool, a list or a numpy array.
    werpy.exceptions.WerpyValueError
        If a reference is blank, either as a single string or as an element of a list, tuple or numpy array, if the
        reference and hypothesis lists, tuples or arrays do not contain the same number of elements, or if a weight
        is negative, NaN, infinite or too large for a float.

    Returns
    -------
    list
        This function will return a list of weighted Word Error Rates, one for each pair of reference and hypothesis
        texts. A pair of strings gives a list that holds one weighted Word Error Rate.

    Examples
    --------
    >>> ref = ['it blocked sight lines of central park', 'her father was an alderman in the city government']
    >>> hyp = ['it blocked sightlines of central park', 'our father was an elder man in the city government']

    >>> werps_example_1 = werps(ref, hyp)
    >>> print(werps_example_1)
    [0.2857142857142857, 0.3333333333333333]

    >>> werps_example_2 = werps(ref, hyp, insertions_weight = 0.5, deletions_weight = 0.5, substitutions_weight = 1)
    >>> print(werps_example_2)
    [0.21428571428571427, 0.2777777777777778]

    >>> werps_example_3 = werps('i love cold pizza', 'i love pizza', 0.5, 0.5, 1)
    >>> print(werps_example_3)
    [0.125]
    """
    reference, hypothesis = error_handler(reference, hypothesis)
    insertions_weight, deletions_weight, substitutions_weight = check_weights(
        insertions_weight, deletions_weight, substitutions_weight
    )
    order = substitution_order(insertions_weight, deletions_weight, substitutions_weight)
    if order:
        result = metrics_fast_weighted(reference, hypothesis, order)
    else:
        result = metrics_fast(reference, hypothesis)

    # Batch: (n, 6) float64
    if isinstance(result, np.ndarray) and result.ndim == 2:
        weighted_insertions = result[:, 3] * insertions_weight
        weighted_deletions = result[:, 4] * deletions_weight
        weighted_substitutions = result[:, 5] * substitutions_weight
        m = result[:, 2]
        weighted_errors = weighted_insertions + weighted_deletions + weighted_substitutions
        out = np.zeros_like(weighted_errors, dtype=np.float64)
        mask = m != 0
        out[mask] = weighted_errors[mask] / m[mask]
        return cast(list[float], out.tolist())

    # Single: (6,) float64
    weighted_insertions = result[3] * insertions_weight
    weighted_deletions = result[4] * deletions_weight
    weighted_substitutions = result[5] * substitutions_weight
    m = result[2]
    weighted_errors = weighted_insertions + weighted_deletions + weighted_substitutions
    return [float(weighted_errors / m) if m else 0.0]
