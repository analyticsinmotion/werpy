"""
This module provides a function for calculating a list of the Word Error Rates for each of the reference and
hypothesis texts.

This module defines the following function:
    - wers(reference, hypothesis)
"""

from typing import cast

import numpy as np
from ._errorhandler import TextInput, error_handler
from ._metrics import metrics_wer_only


def wers(reference: TextInput, hypothesis: TextInput) -> list[float]:
    """
    This function calculates a list of the Word Error Rates for each of the reference and hypothesis texts.

    Parameters
    ----------
    reference : str, list, tuple or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list, tuple or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.

    Raises
    ------
    werpy.exceptions.WerpyTypeError
        If the reference or the hypothesis is not a string, a list, a tuple or a numpy array, if a numpy array does
        not have exactly one dimension, if one of them is a string and the other is a list, a tuple or a numpy array,
        or if an element of a list, tuple or numpy array is not a string, for example a number or None.
    werpy.exceptions.WerpyValueError
        If a reference is blank, either as a single string or as an element of a list, tuple or numpy array, or if
        the reference and hypothesis lists, tuples or arrays do not contain the same number of elements.

    Returns
    -------
    list
        This function will return a list of Word Error Rates, one for each pair of reference and hypothesis texts. A
        pair of strings gives a list that holds one Word Error Rate.

    Example
    --------
    >>> ref = ['no one else could claim that','she cited multiple reasons why']
    >>> hyp = ['no one else could claim that','she sighted multiple reasons why']
    >>> wers_example_1 = wers(ref, hyp)
    >>> print(wers_example_1)
    [0.0, 0.2]

    >>> wers_example_2 = wers('i love cold pizza', 'i love pizza')
    >>> print(wers_example_2)
    [0.25]
    """
    reference, hypothesis = error_handler(reference, hypothesis)
    result = metrics_wer_only(reference, hypothesis)

    # Batch: (n, 3) float64, columns [wer, ld, m]
    if isinstance(result, np.ndarray) and result.ndim == 2:
        return cast(list[float], result[:, 0].tolist())  # Return wer column

    # Single: (3,) float64, WER is at index 0
    return [float(result[0])]
