"""
This module provides a function for calculating the Word Error Rate (WER) between a reference text and a hypothesis 
text. The WER is calculated as the number of edits (insertions, deletions, and substitutions) needed to transform 
the hypothesis text into the reference text, divided by the number of words in the reference text.

This module defines the following function:
    - wer(reference, hypothesis): Calculate the WER between a reference text and a hypothesis text.
"""

import numpy as np
from ._errorhandler import TextInput, error_handler
from ._metrics import metrics_wer_only


def wer(reference: TextInput, hypothesis: TextInput) -> float:
    """
    This function will calculate the overall Word Error Rate for the entire reference and hypothesis texts 
    (i.e., the full corpus).

    Parameters
    ----------
    reference : str, list, tuple or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list, tuple or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.

    Raises
    ------
    werpy.exceptions.WerpyTypeError
        If the reference or the hypothesis is not a string, a list, a tuple or a numpy array, if a numpy array does
        not have exactly one dimension, if one of them is a string and the other is a list, a tuple or a numpy array,
        or if an element of a list, tuple or numpy array is not a string, for example a number or None.
    werpy.exceptions.WerpyValueError
        If a reference is blank, either as a single string or as an element of a list, tuple or numpy array, if the
        reference and hypothesis lists, tuples or arrays do not contain the same number of elements, or if they are
        empty.

    Returns
    -------
    float
        This function will return a single Word Error Rate as a float, which is calculated as the number of edits
        (insertions, deletions, and substitutions) divided by the number of words in the reference text.

    Examples
    --------
    >>> wer_example_1 = wer('i love cold pizza', 'i love pizza')
    >>> print(wer_example_1)
    0.25

    >>> ref = ['i love cold pizza','the sugar bear character was popular']
    >>> hyp = ['i love pizza','the sugar bare character was popular']
    >>> wer_example_2 = wer(ref, hyp)
    >>> print(wer_example_2)
    0.2
    """
    reference, hypothesis = error_handler(reference, hypothesis, allow_empty=False)
    result = metrics_wer_only(reference, hypothesis)

    # Batch: (n, 3) float64, columns [wer, ld, m]
    if isinstance(result, np.ndarray) and result.ndim == 2:
        den = np.sum(result[:, 2])  # m column
        return float(np.sum(result[:, 1]) / den) if den else 0.0  # ld column

    # Single: (3,) float64, WER is at index 0
    return float(result[0])
