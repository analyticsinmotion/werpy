"""
This module provides a function to calculate a weighted Word Error Rate for the entire reference and hypothesis 
texts. It allows varying weights to be assigned to the insertion, deletion and substitution errors.

This module defines the following function:
    - werp(reference, hypothesis, insertions_weight=1, deletions_weight=1, substitutions_weight=1)
"""

import numpy as np
from ._errorhandler import TextInput, error_handler
from ._metrics import metrics_fast


def werp(
    reference: TextInput,
    hypothesis: TextInput,
    insertions_weight: float = 1,
    deletions_weight: float = 1,
    substitutions_weight: float = 1,
) -> float:
    """
    This function calculates a weighted Word Error Rate for the entire reference and hypothesis texts. It allows the
    insertion, deletion and substitution errors to be penalized or weighted at different rates.

    Parameters
    ----------
    reference : str, list or numpy array
        The ground truth transcription of a recorded speech or the expected output of a live speech.
    hypothesis : str, list or numpy array
        The text generated by a speech-to-text algorithm/system which will be compared to the reference text.
    insertions_weight: int or float, optional
        The weight multiplier for an insertion error
    deletions_weight: int or float, optional
        The weight multiplier for a deletion error
    substitutions_weight: int or float, optional
        The weight multiplier for a substitution error

    Raises
    ------
    werpy.exceptions.WerpyTypeError
        If the reference or the hypothesis is not a string, a list or a numpy array, or if one of them is a string
        and the other is a list or a numpy array.
    werpy.exceptions.WerpyValueError
        If a reference is blank, either as a single string or as an element of a list or numpy array, or if the
        reference and hypothesis lists or arrays do not contain the same number of elements.
    TypeError
        If the reference or the hypothesis is a 0-dimensional numpy array, if a weight cannot be multiplied by a
        float, for example None, a string or a Decimal, or if a weight is a list or numpy array and the reference
        and hypothesis are strings.
    ValueError
        If a weight is a list or numpy array whose length differs from the number of elements of the reference and
        hypothesis lists or arrays.
    OverflowError
        If a weight is an int that is too large to convert to a float.
    AttributeError
        If an element of the reference or hypothesis list or array is not a string, for example a number or None.

    Returns
    -------
    float
        This function will return a single weighted Word Error Rate.

    Examples
    --------
    >>> ref = ['it was beautiful and sunny today']
    >>> hyp = ['it was a beautiful and sunny day']

    >>> werp_example_1 = werp(ref, hyp)
    >>> print(werp_example_1)
    0.3333333333333333

    >>> werp_example_2 = werp(ref, hyp, insertions_weight=1, deletions_weight=1, substitutions_weight=1)
    >>> print(werp_example_2)
    0.3333333333333333

    >>> werp_example_3 = werp(ref, hyp, insertions_weight=0.5, deletions_weight=0.5, substitutions_weight=1)
    >>> print(werp_example_3)
    0.25

    >>> werp_example_4 = werp(ref, hyp, 0.5, 0.5, 1)
    >>> print(werp_example_4)
    0.25
    """
    error_handler(reference, hypothesis)
    result = metrics_fast(reference, hypothesis)

    # Batch: (n, 6) float64
    if isinstance(result, np.ndarray) and result.ndim == 2:
        weighted_insertions = result[:, 3] * insertions_weight
        weighted_deletions = result[:, 4] * deletions_weight
        weighted_substitutions = result[:, 5] * substitutions_weight
        m = result[:, 2]
        weighted_errors = weighted_insertions + weighted_deletions + weighted_substitutions
        den = np.sum(m)
        return float(np.sum(weighted_errors) / den) if den else 0.0

    # Single: (6,) float64
    weighted_insertions = result[3] * insertions_weight
    weighted_deletions = result[4] * deletions_weight
    weighted_substitutions = result[5] * substitutions_weight
    m = result[2]
    weighted_errors = weighted_insertions + weighted_deletions + weighted_substitutions
    return float(weighted_errors / m) if m else 0.0
